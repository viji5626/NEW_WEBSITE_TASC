function extractCleanText(code: string): string {
  // Remove import statements
  let clean = code.replace(/import\s+[\s\S]*?from\s+['"][^'"]+['"];?/g, "");
  // Remove interface and type definitions
  clean = clean.replace(/(?:interface|type)\s+[\s\S]*?\{[\s\S]*?\}/g, "");
  // Remove svg/path elements
  clean = clean.replace(/<svg[\s\S]*?<\/svg>/g, "");
  // Remove html/jsx tags
  clean = clean.replace(/<\/?[a-zA-Z0-9_-]+(?:\s+[^>]*?)?>/g, " ");
  // Remove curly brace code blocks like {something ? ... : ...}
  clean = clean.replace(/\{[^}]+\}/g, " ");
  // Clean up excess whitespace and blank lines
  const lines = clean
    .split("\n")
    .map(line => line.trim())
    .filter(line => {
      if (!line) return false;
      if (line.startsWith("//") && !line.includes("LEADERSHIP") && !line.includes("0")) return false;
      if (line.startsWith("const ") && !line.includes("SERVICES") && !line.includes("STACK") && !line.includes("VERTICALS")) return false;
      if (line.startsWith("export ") || line.startsWith("function ") || line.startsWith("return ")) return false;
      return true;
    });

  return lines.join("\n");
}

